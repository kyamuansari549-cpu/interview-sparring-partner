"""Question-bank generator for the Interview Sparring Partner (ispar).

Builds a 10-question mock-interview bank tailored to the candidate's profile:
4 resume deep-dives, 3 CS fundamentals, 2 HR questions and 1 wildcard.
The bank is generated by the LLM and strictly validated — any deviation from
the schema triggers a single repair attempt, then :class:`QuestionBankError`.
No fallback bank is ever fabricated: a bank the model cannot produce correctly
is an error, not a guess.
"""

from __future__ import annotations

import json
import logging
from typing import Any

from .llm import LLMError, chat

log = logging.getLogger(__name__)

CATEGORIES = ("resume_deep_dive", "cs_fundamentals", "hr", "wildcard")

_DIFFICULTIES = ("easy", "medium", "hard")

_BANK_SIZE = 10

_COMPOSITION: dict[str, int] = {
    "resume_deep_dive": 4,
    "cs_fundamentals": 3,
    "hr": 2,
    "wildcard": 1,
}

_REQUIRED_KEYS = ("id", "category", "difficulty", "question", "ideal_points")


class QuestionBankError(Exception):
    """Raised when the LLM fails to produce a valid question bank."""


def _build_messages(profile: dict) -> list[dict]:
    """Build the generation prompt embedding the candidate profile JSON."""
    profile_json = json.dumps(profile, indent=2, ensure_ascii=False, default=str)
    system = (
        "You are an expert technical interview coach preparing a mock-interview "
        "question bank for an Indian IT placement interview. You output only valid JSON."
    )
    user = f"""CANDIDATE PROFILE (JSON):
{profile_json}

Generate EXACTLY 10 interview questions with this composition:
- 4 "resume_deep_dive": technical questions about the candidate's OWN projects and
  technologies, asked the way a sharp interviewer probes a resume. Be specific to the
  profile's actual projects and stack — for example, for an object-detection project
  ask why the NMS IoU threshold is set to 0.5 and what breaks if it is changed; for a
  booking platform ask how seat holds avoid race conditions (atomic operations, DB
  transactions, Redis TTL expiry); for a fine-tuned LLM ask about the LoRA rank choice
  and quantization tradeoffs (q4_k_m vs f16).
- 3 "cs_fundamentals": matched to the candidate's skills — DSA (Big-O analysis,
  data-structure tradeoffs), OS, Computer Networks (e.g. TCP vs UDP), DBMS
  (e.g. indexing, normalization, transactions).
- 2 "hr": the classic HR questions — "tell me about yourself" and "your greatest
  strength and weakness, with a real example".
- 1 "wildcard": one opinion or scenario question, e.g. "how would you explain
  recursion to a 10-year-old".

STRICT SCHEMA RULES — violate any and the output is rejected:
- Output ONLY a JSON array. No markdown fences, no commentary, no extra text.
- Exactly 10 objects, in this order: 4 resume_deep_dive, 3 cs_fundamentals, 2 hr, 1 wildcard.
- Every object has exactly these keys:
  - "id": "q1" through "q10" in order
  - "category": one of "resume_deep_dive", "cs_fundamentals", "hr", "wildcard"
  - "difficulty": one of "easy", "medium", "hard"
  - "question": the interview question text (non-empty string)
  - "ideal_points": 2 to 4 bullet strings listing what a strong answer should cover
- Mix difficulties realistically across the bank (not all the same)."""
    return [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]


def _validate_item(item: Any, index: int) -> None:
    """Validate one question dict; raise QuestionBankError describing the flaw."""
    label = f"question #{index + 1}"
    if not isinstance(item, dict):
        raise QuestionBankError(
            f"{label} is not a JSON object (got {type(item).__name__})"
        )
    for key in _REQUIRED_KEYS:
        if key not in item:
            raise QuestionBankError(f'{label} is missing required key "{key}"')
    if not isinstance(item["id"], str) or not item["id"].strip():
        raise QuestionBankError(f'{label} has an invalid "id": must be a non-empty string')
    if item["category"] not in CATEGORIES:
        raise QuestionBankError(
            f'{label} has invalid category {item["category"]!r}; '
            f"must be one of {CATEGORIES}"
        )
    if item["difficulty"] not in _DIFFICULTIES:
        raise QuestionBankError(
            f'{label} has invalid difficulty {item["difficulty"]!r}; '
            f"must be one of {_DIFFICULTIES}"
        )
    if not isinstance(item["question"], str) or not item["question"].strip():
        raise QuestionBankError(f'{label} has an empty "question"')
    points = item["ideal_points"]
    if (
        not isinstance(points, list)
        or not 2 <= len(points) <= 4
        or any(not isinstance(p, str) or not p.strip() for p in points)
    ):
        raise QuestionBankError(
            f'{label} has an invalid "ideal_points": must be a list of 2-4 non-empty strings'
        )


def _parse_and_validate(raw: str) -> list[dict[str, Any]]:
    """Parse the LLM output and validate it as a full question bank."""
    try:
        data = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise QuestionBankError(f"LLM output is not valid JSON: {exc}") from exc

    if isinstance(data, dict):
        if "questions" not in data:
            raise QuestionBankError(
                'LLM output object has no "questions" key; '
                'expected a JSON list or {"questions": [...]}'
            )
        data = data["questions"]
    if not isinstance(data, list):
        raise QuestionBankError(
            f"LLM output must be a JSON list of questions, got {type(data).__name__}"
        )
    if len(data) != _BANK_SIZE:
        raise QuestionBankError(
            f"expected exactly {_BANK_SIZE} questions, got {len(data)}"
        )

    for index, item in enumerate(data):
        _validate_item(item, index)

    ids = [item["id"] for item in data]
    if set(ids) != {f"q{i + 1}" for i in range(_BANK_SIZE)}:
        raise QuestionBankError(
            f'question ids must be exactly q1..q{_BANK_SIZE} (each once), got {ids}'
        )

    counts: dict[str, int] = {}
    for item in data:
        counts[item["category"]] = counts.get(item["category"], 0) + 1
    if counts != _COMPOSITION:
        raise QuestionBankError(
            f"category composition must be {_COMPOSITION}, got {counts}"
        )

    return data


def _repair_messages(messages: list[dict], raw: str, error: str) -> list[dict]:
    """Build the single repair attempt: show the failure and demand corrected JSON."""
    return messages + [
        {"role": "assistant", "content": raw},
        {
            "role": "user",
            "content": (
                "Your previous output was invalid: " + error + ". "
                "Output ONLY the corrected JSON array — exactly 10 question objects "
                'with keys "id" ("q1".."q10"), "category" (4 resume_deep_dive, '
                '3 cs_fundamentals, 2 hr, 1 wildcard), "difficulty", "question", and '
                '"ideal_points" (2-4 bullets). No explanation, no markdown fences.'
            ),
        },
    ]


def generate_question_bank(profile: dict) -> list[dict[str, Any]]:
    """Generate a validated 10-question interview bank for the candidate profile.

    Raises:
        QuestionBankError: if the LLM call fails, or the output fails JSON
            parsing/schema validation even after one repair attempt.
    """
    messages = _build_messages(profile)

    try:
        raw = chat(messages, temperature=0.7, json_mode=True)
    except LLMError as exc:
        raise QuestionBankError(
            f"LLM call failed while generating the question bank: {exc}"
        ) from exc

    try:
        return _parse_and_validate(raw)
    except QuestionBankError as exc:
        # Bound to a plain variable: `except ... as` names are cleared
        # when the block exits (PEP 3110).
        first_error = exc
        log.warning("Question-bank output invalid, attempting repair: %s", first_error)

    try:
        repaired = chat(
            _repair_messages(messages, raw, str(first_error)),
            temperature=0.7,
            json_mode=True,
        )
    except LLMError as exc:
        raise QuestionBankError(
            f"LLM call failed during question-bank repair: {exc}"
        ) from exc

    return _parse_and_validate(repaired)
